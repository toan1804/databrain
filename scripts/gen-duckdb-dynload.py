#!/usr/bin/env python3
"""Generate crates/duckdb-dynload/src/api.rs from libduckdb-sys's bindings.

Every C function of the DuckDB API gets a `#[no_mangle]` trampoline that
calls the function of the DuckDB library loaded at runtime. Run it again
when the `duckdb` / `libduckdb-sys` version changes:

    python3 scripts/gen-duckdb-dynload.py ~/.cargo/registry/src/*/libduckdb-sys-<version>/src/bindgen_bundled_version.rs
"""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1]).read_text()
out = pathlib.Path(__file__).resolve().parent.parent / "crates/duckdb-dynload/src/api.rs"

def split_top(s, sep=","):
    parts, depth, cur = [], 0, ""
    for ch in s:
        if ch in "(<[": depth += 1
        elif ch in ")>]": depth -= 1
        if ch == sep and depth == 0:
            parts.append(cur); cur = ""
        else:
            cur += ch
    if cur.strip(): parts.append(cur)
    return [p.strip() for p in parts if p.strip()]

fns = []
for m in re.finditer(r"pub fn (duckdb_\w+)\(", src):
    name, i, depth = m.group(1), m.end(), 1
    j = i
    while depth:
        c = src[j]
        if c == "(": depth += 1
        elif c == ")": depth -= 1
        j += 1
    params = src[i:j - 1]
    rest = src[j:src.index(";", j)].strip()
    ret = rest[2:].strip() if rest.startswith("->") else ""
    args = []
    for p in split_top(params):
        n, t = p.split(":", 1)
        args.append((n.strip(), " ".join(t.split())))
    fns.append((name, args, " ".join(ret.split())))

lines = [
    "// @generated by scripts/gen-duckdb-dynload.py — do not edit.",
    "#![allow(clippy::all, non_snake_case, unused_unsafe)]",
    "use libduckdb_sys::*;",
    "use super::sym;",
    "",
    f"pub(crate) const NAMES: [&str; {len(fns)}] = [",
    *[f'    "{n}",' for n, _, _ in fns],
    "];",
    "",
]
for idx, (name, args, ret) in enumerate(fns):
    sig = ", ".join(f"{n}: {t}" for n, t in args)
    tys = ", ".join(t for _, t in args)
    call = ", ".join(n for n, _ in args)
    r = f" -> {ret}" if ret else ""
    lines += [
        "#[unsafe(no_mangle)]",
        f"pub unsafe extern \"C\" fn {name}({sig}){r} {{",
        f"    let f: unsafe extern \"C\" fn({tys}){r} = unsafe {{ std::mem::transmute(sym({idx})) }};",
        f"    unsafe {{ f({call}) }}",
        "}",
    ]
out.write_text("\n".join(lines) + "\n")
print(f"{len(fns)} functions → {out}")
