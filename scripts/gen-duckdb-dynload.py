#!/usr/bin/env python3
"""Generate crates/duckdb-dynload/src/api/ from libduckdb-sys's bindings.

The trampolines are grouped into one module per area of the C API (see GROUPS);
`names.rs` holds the symbol table and `mod.rs` declares the modules. Every C
function of the DuckDB API gets a `#[no_mangle]` trampoline that
calls the function of the DuckDB library loaded at runtime. Run it again
when the `duckdb` / `libduckdb-sys` version changes:

    python3 scripts/gen-duckdb-dynload.py ~/.cargo/registry/src/*/libduckdb-sys-<version>/src/bindgen_bundled_version.rs
"""
import re, sys, pathlib

src = pathlib.Path(sys.argv[1]).read_text()
out = pathlib.Path(__file__).resolve().parent.parent / "crates/duckdb-dynload/src/api"

# (module, regex on the function name); the first match wins.
GROUPS = [
    ("aggregate", r"duckdb_(create_aggregate|destroy_aggregate|aggregate_)"),
    ("appender", r"duckdb_(appender|append_|create_appender|destroy_appender)"),
    ("arrow", r"duckdb_.*arrow"),
    ("cast", r"duckdb_.*cast"),
    ("copy_function", r"duckdb_.*copy_function"),
    ("scalar_function", r"duckdb_.*scalar_function"),
    ("table_function", r"duckdb_.*(table_function|bind_|init_)"),
    ("replacement_scan", r"duckdb_.*replacement"),
    ("table_description", r"duckdb_.*table_description"),
    ("expression", r"duckdb_.*expression"),
    ("log_storage", r"duckdb_.*(log_storage|logger)"),
    ("file_system", r"duckdb_.*(file_system|file_handle|file_open|file_flag)"),
    ("pending", r"duckdb_.*(pending|execute_tasks|interrupt|query_progress)|duckdb_task_state"),
    ("task", r"duckdb_.*task"),
    ("prepared", r"duckdb_.*(prepare|prepared|nparams|param_|clear_bindings|bind)"),
    ("result", r"duckdb_.*(result|column_|row_count|rows_changed|nullmask|value_)"),
    ("logical_type", r"duckdb_.*(logical_type|_type_|enum_|struct_type|union_type|decimal_)"),
    ("vector", r"duckdb_.*(vector|chunk|validity|selection)"),
    ("datetime_conv", r"duckdb_.*(date|time|interval|hugeint|uhugeint|decimal|bignum)"),
    ("value", r"duckdb_.*value|duckdb_(create|get)_"),
    ("connection", r"duckdb_.*(connect|disconnect|client_context|extract_statements|extracted|query)"),
    ("database", r"duckdb_.*(database|config|library_version|platform|instance_cache)"),
    ("memory_string", r"duckdb_(malloc|free|string|destroy_)"),
]

def group_of(name):
    for mod, rx in GROUPS:
        if re.fullmatch(rx + ".*", name):
            return mod
    return "misc"

def split_top(s, sep=","):
    parts, depth, cur = [], 0, ""
    for ch in s:
        if ch in "(<[": depth += 1
        elif ch in ")>]": depth -= 1
        if ch == sep and depth == 0:
            parts.append(cur); cur = ""
        else:
            cur += ch
    if cur.strip(): parts.append(cur)
    return [p.strip() for p in parts if p.strip()]

fns = []
for m in re.finditer(r"pub fn (duckdb_\w+)\(", src):
    name, i, depth = m.group(1), m.end(), 1
    j = i
    while depth:
        c = src[j]
        if c == "(": depth += 1
        elif c == ")": depth -= 1
        j += 1
    params = src[i:j - 1]
    rest = src[j:src.index(";", j)].strip()
    ret = rest[2:].strip() if rest.startswith("->") else ""
    args = []
    for p in split_top(params):
        n, t = p.split(":", 1)
        args.append((n.strip(), " ".join(t.split())))
    fns.append((name, args, " ".join(ret.split())))

HEADER = "// @generated by scripts/gen-duckdb-dynload.py — do not edit.\n"
out.mkdir(exist_ok=True)
for old in out.glob("*.rs"):
    old.unlink()

groups = {}
for idx, (name, args, ret) in enumerate(fns):
    sig = ", ".join(f"{n}: {t}" for n, t in args)
    tys = ", ".join(t for _, t in args)
    call = ", ".join(n for n, _ in args)
    r = f" -> {ret}" if ret else ""
    groups.setdefault(group_of(name), []).extend([
        "#[unsafe(no_mangle)]",
        f"pub unsafe extern \"C\" fn {name}({sig}){r} {{",
        f"    let f: unsafe extern \"C\" fn({tys}){r} = unsafe {{ std::mem::transmute(sym({idx})) }};",
        f"    unsafe {{ f({call}) }}",
        "}",
    ])
for mod, body in groups.items():
    (out / f"{mod}.rs").write_text(HEADER + "use crate::sym;\nuse libduckdb_sys::*;\n\n" + "\n".join(body) + "\n")

names = [f'    "{n}",' for n, _, _ in fns]
(out / "names.rs").write_text(HEADER + f"pub(crate) const NAMES: [&str; {len(fns)}] = [\n" + "\n".join(names) + "\n];\n")
mods = "".join(f"mod {m};\n" for m in sorted(list(groups) + ["names"]))
(out / "mod.rs").write_text(HEADER + "#![allow(clippy::all, non_snake_case, unused_unsafe)]\n\n" + mods + "\npub(crate) use names::NAMES;\n")
print(f"{len(fns)} functions in {len(groups)} modules → {out}")
